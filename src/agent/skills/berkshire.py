class BerkshireSkills:
    def __init__(self, model: str | None = None) -> None:
        self._client = LLMClient(model=model)

    def execute(self, name: str, args: dict) -> str:
        handler = getattr(self, f"_skill_{name}", None)
        if not handler:
            return f'{{"error": "Unknown skill: {name}"}}'
        try:
            return handler(**args)
        except Exception as e:
            log.exception("Skill %s failed", name)
            return f'{{"error": "{e}"}}'

    def _call_llm(self, system: str, user_msg: str) -> str:
        response = self._client.chat(
            system=system,
            messages=[{"role": "user", "content": user_msg}],
        )
        return response.text or ""

    def _skill_value_checklist(self, company: str, market: str | None = None) -> str:
        market_context = ""
        if market:
            market_map = {
                "US": "美国市场",
                "HK": "香港市场",
                "A": "A股市场",
                "JP": "日本市场",
                "UK": "英国市场",
            }
            market_text = market_map.get(market, f"{market}市场")
            market_context = f"市场: {market_text}（请结合该市场特点分析）"
        prompt = _SKILL_PROMPTS["value_checklist"].format(
            company=company, market_context=market_context
        )
        return self._call_llm(
            prompt, f"请对 {company} 进行巴菲特六道门投资检查清单分析。"
        )

    def _skill_four_masters(self, company: str, focus: str = "full") -> str:
        focus_text = "完整四大师深度分析" if focus == "full" else "快速要点分析（每位大师3-5句关键判断）"
        prompt = _SKILL_PROMPTS["four_masters"].format(
            company=company, focus_text=focus_text
        )
        return self._call_llm(
            prompt, f"请对 {company} 进行四大师视角综合分析。"
        )

    def _skill_quality_screen(
        self, companies: str, sector: str | None = None
    ) -> str:
        sector_context = ""
        if sector:
            sector_context = f"行业: {sector}（请结合行业特性判断豁免规则适用性）"
        prompt = _SKILL_PROMPTS["quality_screen"].format(
            companies=companies, sector_context=sector_context
        )
        return self._call_llm(
            prompt,
            f"请对以下公司进行七指标质量筛选: {companies}",
        )

    def _skill_devils_advocate(self, company: str, bull_thesis: str) -> str:
        prompt = _SKILL_PROMPTS["devils_advocate"].format(
            company=company, bull_thesis=bull_thesis
        )
        return self._call_llm(
            prompt,
            f"请对 {company} 的以下看多论点进行芒格式逆向分析：{bull_thesis}",
        )
